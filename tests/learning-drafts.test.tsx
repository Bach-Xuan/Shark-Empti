import { act, cleanup, fireEvent, render, renderHook, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import QuizView from '@/components/quiz-view';
import { useLearningSession } from '@/hooks/use-learning-session';
import { DRAFT_TTL_MS, readDraft, writeDraft, pruneDraftsForOwner } from '@/lib/draft-storage';
import { parseWith, quizDraftSchema, sessionDraftSchema } from '@/lib/learning-drafts';
import { translations } from '@/lib/translations';
import { history, question, analysis } from './fixtures/quiz';
import type { Firestore } from 'firebase/firestore';
const mocks = vi.hoisted(() => ({ feedback: vi.fn(), write: vi.fn() }));
vi.mock('@/ai/client-flows', () => ({ personalizedQuizPerformanceFeedback: mocks.feedback, generateQuestions: vi.fn(), shortAnswerAnalysis: vi.fn() }));
vi.mock('@/lib/error-toast', () => ({ showErrorToast: vi.fn() }));
vi.mock('@/firebase/error-emitter', () => ({ errorEmitter: { emit: vi.fn() } }));
vi.mock('firebase/firestore', () => ({ doc: (...parts: string[]) => ({ path: parts.slice(1).join('/') }), setDoc: mocks.write }));
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.clearAllMocks(); });

it('isolates accounts, removes previous-owner drafts at Auth boundaries, and never touches unrelated browser preferences', () => {
  const parse = (value: unknown) => typeof value === 'string' ? value : null;
  sessionStorage.setItem('unrelated', 'retained');
  expect(writeDraft('first', 'quiz', 'private')).toBe(true);
  expect(readDraft('second', 'quiz', parse)).toBeNull();
  writeDraft('second', 'quiz', 'other');
  pruneDraftsForOwner('second');
  expect(readDraft('first', 'quiz', parse)).toBeNull();
  expect(readDraft('second', 'quiz', parse)).toBe('other');
  pruneDraftsForOwner(null);
  expect(readDraft('second', 'quiz', parse)).toBeNull();
  expect(sessionStorage.getItem('unrelated')).toBe('retained');
});
it('rejects expired, malformed, oversized and unavailable storage without crashing learning', () => {
  const parse = (value: unknown) => typeof value === 'string' ? value : null;
  const now = Date.now();
  writeDraft('owner', 'quiz', 'content');
  vi.spyOn(Date, 'now').mockReturnValue(now + DRAFT_TTL_MS + 1);
  expect(readDraft('owner', 'quiz', parse)).toBeNull();
  vi.restoreAllMocks();
  sessionStorage.setItem('shark:draft:v1:owner:quiz', '{');
  expect(readDraft('owner', 'quiz', parse)).toBeNull();
  expect(writeDraft('owner', 'quiz', 'x'.repeat(1_000_001))).toBe(false);
  vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new DOMException('Quota', 'QuotaExceededError'); });
  expect(writeDraft('owner', 'quiz', 'text')).toBe(false);
});
it('restores generated questions and the original stable history identity without generation or duplicate archives', async () => {
  const id = crypto.randomUUID();
  const draft = { id, config: history.config, questions: [question] };
  expect(sessionDraftSchema.safeParse(draft).success).toBe(true);
  writeDraft('learner', 'quiz-session', draft);
  mocks.write.mockResolvedValue(undefined);
  const { result } = renderHook(() => useLearningSession({ uid: 'learner' }, {} as Firestore, 'en'));
  expect(result.current.session.status).toBe('quiz');
  expect(result.current.draftId).toBe(id);
  await act(async () => { expect(await result.current.finish(history)).toBe(true); });
  expect(mocks.write.mock.calls[0][0].path).toBe(`users/learner/history/${id}`);
  expect(readDraft('learner', 'quiz-session', parseWith(sessionDraftSchema))).toBeNull();
});
it('resumes the current question and failed completion, preserving feedback without another paid analysis', async () => {
  const id = crypto.randomUUID();
  const second = { ...question, question: '3+3?', correct: '6', options: ['6', '5', '4', '3'] };
  const config = { ...history.config, numQuestions: '2' };
  writeDraft('learner', 'quiz-progress', { id, index: 1, answers: history.quizResults, feedback: null, input: '', startedAtMs: Date.now() - 2000, questionStartedAtMs: Date.now() - 1000 });
  mocks.feedback.mockResolvedValue({ ok: true, data: { ...analysis, topicEn: 'Addition', topicVi: 'Phép cộng' } });
  const finish = vi.fn().mockResolvedValueOnce(false).mockResolvedValue(true);
  const props = { t: translations.en, lang: 'en', config, initialQuestions: [question, second], draftOwner: 'learner', draftId: id, onFinish: finish, onAskGuru: vi.fn() };
  const first = render(<QuizView {...props} />);
  expect(screen.getByText('3+3?')).toBeTruthy();
  const unload = new Event('beforeunload', { cancelable: true });
  window.dispatchEvent(unload); expect(unload.defaultPrevented).toBe(true);
  fireEvent.click(screen.getByRole('button', { name: '6' }));
  fireEvent.click(screen.getByRole('button', { name: /finish|results/i }));
  await waitFor(() => expect(finish).toHaveBeenCalledTimes(1));
  await screen.findByRole('button', { name: 'Retry' });
  expect(readDraft('learner', 'quiz-progress', parseWith(quizDraftSchema))?.completion).toBeTruthy();
  first.unmount();
  render(<QuizView {...props} />);
  fireEvent.click(await screen.findByRole('button', { name: 'Retry' }));
  await waitFor(() => expect(finish).toHaveBeenCalledTimes(2));
  expect(mocks.feedback).toHaveBeenCalledTimes(1);
  expect(finish.mock.calls[1][0].quizResults.map((item: { userAnswer: string }) => item.userAnswer)).toEqual(['4', '6']);
  expect(finish.mock.calls[1][1]).toMatchObject(analysis);
});
